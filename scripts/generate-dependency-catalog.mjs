#!/usr/bin/env node
// Maintainer tool: regenerates (or checks) src/application/dependency-reuse/catalog.ts from
// explicitly supplied local reference data. It never fetches anything, installs packages,
// executes reference scripts or reads a target project. Run `pnpm build` first: the trusted
// parser session needs the packaged worker.
//
//   node scripts/generate-dependency-catalog.mjs generate --reference-root <dir>
//   node scripts/generate-dependency-catalog.mjs check    --reference-root <dir>
//
// <dir> holds one directory per reference, named `<alias>@<tag>`, containing the upstream files at
// their repository paths. Every file is verified against the SHA-256 in the reviewed manifest
// before it is parsed; the manifest also pins the immutable commit each tag resolved to.
import { createHash } from 'node:crypto';
import { lstat, readFile, realpath, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format } from 'oxfmt';
import { z } from 'zod';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST_PATH = join(ROOT, 'scripts/dependency-references.json');
const CATALOG_PATH = join(ROOT, 'src/application/dependency-reuse/catalog.ts');
const MAX_REFERENCE_FILE_BYTES = 2 * 1024 * 1024;
const MAX_ID_LENGTH = 128;

const sha256 = z.string().regex(/^[0-9a-f]{64}$/u);
const manifestSchema = z.strictObject({
  manifestVersion: z.literal(1),
  catalogVersion: z.string().regex(/^\d+\.\d+\.\d+$/u),
  references: z
    .array(
      z.strictObject({
        alias: z.string().regex(/^[a-z][a-z0-9-]*$/u),
        repository: z.string().regex(/^https:\/\/github\.com\/[A-Za-z0-9._-]+\/[A-Za-z0-9._-]+$/u),
        tag: z.string().regex(/^[A-Za-z0-9._-]+$/u),
        commit: z.string().regex(/^[0-9a-f]{40}$/u),
        license: z.string().min(1).max(64),
        files: z
          .array(
            z.strictObject({
              path: z
                .string()
                .regex(/^(?!\/)(?!.*(?:^|\/)\.\.?(?:\/|$))(?!.*\/\/)[A-Za-z0-9_./-]+\.sol$/u),
              sha256,
            }),
          )
          .min(1),
      }),
    )
    .min(1),
});

function usage() {
  throw new Error(
    'Usage: node scripts/generate-dependency-catalog.mjs generate|check --reference-root <dir>',
  );
}

function parseArguments(argv) {
  const mode = argv[0];
  if (mode !== 'generate' && mode !== 'check') usage();
  if (argv.length !== 3 || argv[1] !== '--reference-root' || argv[2] === undefined) usage();
  return { mode, referenceRoot: argv[2] };
}

function inside(parent, child) {
  const path = relative(parent, child);
  return path !== '' && !path.startsWith(`..${sep}`) && path !== '..' && !isAbsolute(path);
}

function compare(left, right) {
  const a = Array.from(left, (scalar) => scalar.codePointAt(0) ?? 0);
  const b = Array.from(right, (scalar) => scalar.codePointAt(0) ?? 0);
  for (let index = 0; index < Math.min(a.length, b.length); index += 1) {
    if (a[index] !== b[index]) return (a[index] ?? 0) - (b[index] ?? 0);
  }
  return a.length - b.length;
}

async function readReference(referenceRoot, directory, path) {
  const absolute = resolve(referenceRoot, directory, ...path.split('/'));
  if (!inside(referenceRoot, absolute)) throw new Error(`Reference path escapes the root: ${path}`);
  const info = await lstat(absolute);
  if (!info.isFile()) throw new Error(`Reference is not a regular file: ${path}`);
  if (info.size > MAX_REFERENCE_FILE_BYTES) throw new Error(`Reference file is too large: ${path}`);
  const physical = await realpath(absolute);
  if (!inside(referenceRoot, physical)) throw new Error(`Reference path escapes the root: ${path}`);
  return await readFile(physical);
}

function literal(value) {
  return JSON.stringify(value);
}

function emit(catalog) {
  return `// Generated by scripts/generate-dependency-catalog.mjs from scripts/dependency-references.json.
// Do not edit by hand. Regenerate and review the diff whenever a reference or the parser changes.
import type { DependencyCatalog } from './types.ts';

/** Reviewed immutable upstream declaration digests; see docs/dependency-reuse.md for provenance. */
export const BUNDLED_CATALOG: DependencyCatalog = ${literal(catalog)};
`;
}

async function formatted(code) {
  const config = JSON.parse(await readFile(join(ROOT, '.oxfmtrc.json'), 'utf8'));
  const options = {
    printWidth: config.printWidth,
    tabWidth: config.tabWidth,
    useTabs: config.useTabs,
    semi: config.semi,
    singleQuote: config.singleQuote,
    trailingComma: config.trailingComma,
  };
  const result = await format('catalog.ts', code, options);
  if (result.errors.length > 0) throw new Error('Cannot format the generated catalog.');
  return result.code;
}

async function main() {
  const { mode, referenceRoot: suppliedRoot } = parseArguments(process.argv.slice(2));
  const referenceRoot = await realpath(resolve(suppliedRoot));
  const manifest = manifestSchema.parse(JSON.parse(await readFile(MANIFEST_PATH, 'utf8')));

  const load = (path) => import(pathToFileURL(join(ROOT, path)).href);
  const [
    { createParserSession },
    { createDiscoveryBudget },
    { mergeConfig },
    defaults,
    canonical,
    reuse,
    metrics,
  ] = await Promise.all([
    load('src/parser/adapter.ts'),
    load('src/discovery/budget.ts'),
    load('src/config/merge.ts'),
    load('src/application/defaults.ts'),
    load('src/domain/canonical.ts'),
    load('src/application/dependency-reuse/fingerprint.ts'),
    load('src/metrics/structural.ts'),
  ]);
  const config = mergeConfig({ defaults: defaults.productionConfigDefaults() }).config;
  const budget = createDiscoveryBudget(config.analysis.limits);
  const session = createParserSession({ budget, config });
  const files = [];
  const declarations = [];
  const grammarSets = [];
  let parserVersion = null;
  const ids = new Set();
  try {
    for (const reference of manifest.references) {
      const directory = `${reference.alias}@${reference.tag}`;
      for (const entry of reference.files) {
        const bytes = await readReference(referenceRoot, directory, entry.path);
        const digest = createHash('sha256').update(bytes).digest('hex');
        if (digest !== entry.sha256) {
          throw new Error(`Hash mismatch for ${directory}/${entry.path}: ${digest}`);
        }
        const text = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
        const canonicalPath = `${reference.alias}-${reference.tag}/${entry.path}`;
        const fileId = canonical.fileIdentity(canonicalPath);
        const source = {
          fileId,
          snapshot: {
            canonicalPath,
            absolutePath: join(referenceRoot, directory, entry.path),
            originalBytes: bytes,
            originalText: text,
            byteHash: digest,
          },
          manifestEntry: {
            fileId,
            path: canonicalPath,
            role: 'scoped',
            ownership: 'first-party',
            ownershipEvidence: [],
            physicalIdentity: canonicalPath,
            byteHash: digest,
          },
        };
        const batch = await session.analyzeSources([source]);
        const result = batch.files[0];
        if (result === undefined || result.status !== 'parsed') {
          throw new Error(`Reference did not parse: ${directory}/${entry.path}`);
        }
        if (parserVersion === null) parserVersion = result.version.parserVersion;
        if (parserVersion !== result.version.parserVersion) {
          throw new Error('The parser version changed during generation.');
        }
        const raw = metrics.buildFileMetrics(source, result);
        const index = reuse.indexTokens(
          result.tokens,
          result.events.filter((event) => event.kind === 'assembly').map((event) => event.range),
        );
        const pragma = result.version.pragmaRanges
          .map((range) =>
            Buffer.from(bytes.subarray(range.startByte, range.endByte)).toString('utf8').trim(),
          )
          .join(' ');
        const id = `${reference.alias}@${reference.tag}:${entry.path}`;
        const fileIndex = files.length;
        const compatible = [...result.version.compatibleVersions];
        const key = JSON.stringify(compatible);
        let grammarSet = grammarSets.findIndex((set) => JSON.stringify(set) === key);
        if (grammarSet < 0) {
          grammarSet = grammarSets.length;
          grammarSets.push(compatible);
        }
        files.push({
          id,
          repository: reference.repository,
          tag: reference.tag,
          commit: reference.commit,
          path: entry.path,
          sha256: digest,
          license: reference.license,
          pragma: pragma.slice(0, 128),
          selectedGrammar: result.version.selectedVersion,
          grammarSet,
        });
        for (const contract of raw.contracts) {
          const referenceId = `${id}#${contract.name}`;
          if (referenceId.length > MAX_ID_LENGTH || ids.has(referenceId)) {
            throw new Error(`Reference ID is too long or duplicated: ${referenceId}`);
          }
          ids.add(referenceId);
          const fingerprint = await reuse.fingerprintDeclaration(
            index,
            bytes,
            { kind: contract.kind, name: contract.name, range: contract.range },
            () => budget.checkpoint(),
          );
          declarations.push({
            file: fileIndex,
            kind: contract.kind,
            name: contract.name,
            digest: fingerprint.digest,
            tokenCount: fingerprint.tokenCount,
          });
        }
      }
    }
  } finally {
    await session.close();
  }
  if (parserVersion === null) throw new Error('No reference was processed.');

  // Deterministic order: files by ID, declarations by file then name.
  const order = files
    .map((file, index) => ({ file, index }))
    .sort((l, r) => compare(l.file.id, r.file.id));
  const remap = new Map(order.map((item, position) => [item.index, position]));
  const sortedFiles = order.map((item) => item.file);
  const sortedDeclarations = declarations
    .map((item) => ({ ...item, file: remap.get(item.file) ?? -1 }))
    .sort((l, r) => l.file - r.file || compare(l.name, r.name) || compare(l.kind, r.kind));
  const body = {
    status: 'available',
    version: manifest.catalogVersion,
    parserVersion,
    normalizerVersion: reuse.NORMALIZER_VERSION,
    grammarSets,
    files: sortedFiles,
    declarations: sortedDeclarations,
  };
  const catalog = { ...body, digest: reuse.computeCatalogDigest(body) };
  const code = await formatted(emit(catalog));
  if (mode === 'generate') {
    await writeFile(CATALOG_PATH, code, 'utf8');
    process.stdout.write(
      `Generated ${CATALOG_PATH}: ${sortedFiles.length} files, ${sortedDeclarations.length} declarations, catalog ${catalog.digest}\n`,
    );
    return;
  }
  const committed = await readFile(CATALOG_PATH, 'utf8');
  if (committed !== code) throw new Error('Catalog drift: regenerate and review the diff.');
  process.stdout.write(`Catalog check passed: ${catalog.digest}\n`);
}

try {
  await main();
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
}
